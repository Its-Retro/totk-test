import sys, os, hashlib
out = ['/* Generated by bc7-shaders/build.sh from bc7-shaders/bc7_encode.hlsl (DXC, cs_6_0): do not edit.',
       ' * BC7 encoder ported from Microsoft DirectXTex BC7Encode.hlsl (MIT; THIRD-PARTY-NOTICES.md). */',
       '#ifndef TOTK_HOST_BC7_DXIL_H', '#define TOTK_HOST_BC7_DXIL_H', '#include <stdint.h>']
for path in sys.argv[1:]:
    b = open(path, 'rb').read()
    name = 'boot_bc7_' + os.path.basename(path).split('.')[0][4:] + '_dxil'
    out.append('/* %s: %d bytes, sha256 %s */' % (os.path.basename(path), len(b), hashlib.sha256(b).hexdigest()))
    out.append('static const uint8_t %s[%d] = {' % (name, len(b)))
    for i in range(0, len(b), 24):
        out.append('    ' + ','.join('0x%02x' % c for c in b[i:i + 24]) + ',')
    out.append('};')
out.append('#endif')
sys.stdout.buffer.write(('\r\n'.join(out) + '\r\n').encode('ascii'))   # CRLF like the other startup headers, on any platform
