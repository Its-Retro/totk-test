"""G2 (batch-4) point sprites: one geometry shader per vertex-shader output signature (host_gpu_render_draw.h boot_pt_apply).

D3D12 draws a point as one pixel and has no point coordinate; NVN draws a point_size x point_size square and gives the
fragment shader gl_PointCoord (nxport crates/engine/src/metal/mod.rs:2700-2705, metal/msl_specialize.rs:375-379: Metal
does it natively; only these semantics are taken from nxport). For a POINTS draw whose pixel shader reads POINTCOORD the
host binds a geometry shader that turns the point into that square. Its input must equal the vertex shader's output
signature element for element, so the shaders are generated from the signatures themselves: every VS row of
shader-manifest.tsv, its DXIL's OSG1 part (signature elements), grouped by FNV-1a 64 of the part's bytes (the host hashes
the same bytes at draw time). Per group: <out>/pt-<key>.hlsl and pt-<key>.gs.dxil (dxc, the flags of
translate_game_shaders.compile_dxc with -T gs_6_6), checked after compiling: the geometry shader's ISG1 equals the vertex
shader's OSG1 (name, index, system value, component type, register, mask), and its OSG1 has every vertex output in the
same register plus POINTCOORD. Pixel shaders of the manifest that read POINTCOORD are checked against the layouts whose
generics they declare. Writes <out>/point-gs.tsv (key, vertex shaders, example, file).
Streams one DXIL file at a time. Never touches the shader folders it reads. --stage DIR: a manifest file that has a copy at
DIR/<its path relative to startup> (a retranslated set not swapped in yet) is read from there. dxc runs at below-normal
priority.
usage: make_point_gs.py [--out DIR] [--limit N] [--only KEY] [--jobs N] [--root STARTUP] [--stage DIR]
       (default DIR: startup/shader-gs)
"""
import os, struct, subprocess, sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
ROOT = Path(sys.argv[sys.argv.index('--root') + 1]) if '--root' in sys.argv else Path(__file__).resolve().parent   # startup
DXC = ROOT.parent / 'tools' / 'dxc' / 'bin' / 'x64' / 'dxc.exe'

def part(path, fourcc):
    with open(path, 'rb') as f:
        head = f.read(32)
        if len(head) < 32 or head[:4] != b'DXBC': return None
        n = struct.unpack_from('<I', head, 28)[0]
        for o in struct.unpack('<%dI' % n, f.read(4 * n)):
            f.seek(o); cc, size = struct.unpack('<4sI', f.read(8))
            if cc == fourcc: return f.read(size)
    return None

def fnv64(b):
    h = 0xcbf29ce484222325
    for x in b: h = ((h ^ x) * 0x100000001b3) & 0xffffffffffffffff
    return h or 1

def elements(data):
    """(name, index, system value, component type, register, mask) per element, in signature order."""
    count, off = struct.unpack_from('<II', data, 0); out = []
    for i in range(count):
        _stream, name, idx, sv, ct, reg, mask, _rw, _pad, _mp = struct.unpack_from('<6IBBHI', data, off + 32 * i)
        out.append((data[name:data.index(b'\0', name)].decode(), idx, sv, ct, reg, mask))
    return out

TYPES = {1: 'uint', 2: 'int', 3: 'float'}
def decl(e, k):
    name, idx, sv, ct, reg, mask = e
    m = mask >> ((mask & -mask).bit_length() - 1) if mask else 0   # packed elements may start past x: DXC repacks the same
    if not m or m & (m + 1): raise ValueError(f'element {name}{idx} mask {mask:#x}: not contiguous')   # declarations alike
    n = bin(mask).count('1'); t = TYPES.get(ct)
    if t is None: raise ValueError(f'element {name}{idx}: component type {ct}')
    sem = name if name.startswith('SV_') and name not in ('SV_ClipDistance', 'SV_CullDistance') else f'{name}{idx}'
    return f'{t}{n if n > 1 else ""} e{k} : {sem}', n

def hlsl(key, els, count, example):
    """Geometry shader source for one output signature."""
    pos = [k for k, e in enumerate(els) if e[0] == 'SV_Position']
    if len(pos) != 1: raise ValueError('no single SV_Position output')
    psize = [k for k, e in enumerate(els) if e[0] == 'PSIZE' and e[3] == 3]
    user = [k for k, e in enumerate(els) if not e[0].startswith('SV_') and k not in psize]   # PSIZE: consumed here
    system = [k for k, e in enumerate(els) if e[0].startswith('SV_') and k not in pos]
    L = ['// G2 (batch-4) point sprites: generated by make_point_gs.py, do not edit (host_gpu_render_draw.h boot_pt_apply).',
         f'// Vertex-shader output signature {key:016x}: {count} vertex shaders of the manifest, e.g. {example}.',
         '// Each point of a POINTS draw becomes a point_size x point_size square (two triangles) with the vertex outputs',
         '// unchanged and POINTCOORD 0..1 across it, as NVN rasterises points (nxport metal/mod.rs:2700-2705,',
         '// msl_specialize.rs:375-379, semantics only). Parameters: entry 32 of the vertex attribute table.',
         'struct VertexAttrib { uint2 stream_va; uint stride, offset, format, divisor, size, pad; };',
         'StructuredBuffer<VertexAttrib> vertex_attribs : register(t2, space0);',
         'struct VsOut {']
    for k, e in enumerate(els): L.append('    ' + decl(e, k)[0] + ';')
    L.append('};')
    # Output: position, the user outputs in their order, POINTCOORD, then the system values. A pixel shader declares
    # SV_Position, its generics (the vertex shader's output map, in order) and POINTCOORD (translate_game_shaders.py
    # assemble), so its inputs are a prefix of this signature, register for register.
    L.append('struct GsOut {')
    for k in pos + user: L.append('    ' + decl(els[k], k)[0] + ';')
    L.append('    float2 pointcoord : POINTCOORD;')
    for k in system: L.append('    ' + decl(els[k], k)[0] + ';')
    L.append('};')
    L += ['[maxvertexcount(4)]',
          'void main(point VsOut v[1], inout TriangleStream<GsOut> s) {',
          '    VertexAttrib p = vertex_attribs[32];   // size, viewport half width, half height (pixels), flags',
          f'    float4 c = v[0].e{pos[0]};',
          '    if (!(abs(c.x) <= c.w && abs(c.y) <= c.w)) return;   // centre outside the view volume (x/y): the point is not drawn',
          f'    float size = clamp({f"v[0].e{psize[0]}" if psize else "asfloat(p.stream_va.x)"}, 1.0f, 2047.0f);',
          '    float2 h = 0.5f * size / float2(asfloat(p.stream_va.y), asfloat(p.stride)) * c.w;   // half size in clip units',
          '    bool ccw = (p.offset & 1u) != 0u, up = (p.offset & 2u) != 0u;',
          '    GsOut o;']
    for k in user + system: L.append(f'    o.e{k} = v[0].e{k};')
    L += ['    [unroll] for (uint k = 0u; k < 4u; ++k) {',
          '        uint q = ccw && (k == 1u || k == 2u) ? 3u - k : k;   // strip TL TR BL BR (clockwise) or TL BL TR BR',
          '        float2 d = float2((q & 1u) != 0u ? 1.0f : -1.0f, (q & 2u) != 0u ? -1.0f : 1.0f);   // +y: the upper rows',
          f'        o.e{pos[0]} = float4(c.xy + d * h, c.zw);',
          '        o.pointcoord = float2(0.5f + 0.5f * d.x, up ? 0.5f + 0.5f * d.y : 0.5f - 0.5f * d.y);',
          '        s.Append(o);',
          '    }',
          '}']
    return '\n'.join(L) + '\n'

def compile_gs(src_path, out_path):
    cmd = [str(DXC), '-nologo', '-T', 'gs_6_6', '-E', 'main', '-HV', '2021', '-O3', '-Gis', '-Fo', str(out_path), str(src_path)]
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=300, creationflags=0x00004000)   # BELOW_NORMAL_PRIORITY_CLASS
    return r.returncode, (r.stderr + r.stdout).strip()

def check(key, els, gs_path):
    isg = part(gs_path, b'ISG1'); osg = part(gs_path, b'OSG1')
    if isg is None or osg is None: return 'no signature parts'
    gi = elements(isg)
    if gi != els: return f'input signature differs: {gi} vs {els}'
    go = elements(osg); byname = {(e[0], e[1]): e for e in go}
    for e in els:
        o = byname.get((e[0], e[1]))
        if (e[0].startswith('SV_') and e[0] != 'SV_Position') or e[0] == 'PSIZE': continue
        if not o or o[4] != e[4] or o[5] != e[5]: return f'output {e[0]}{e[1]} moved: {o} vs {e}'
    if ('POINTCOORD', 0) not in byname: return 'no POINTCOORD output'
    return None

def main():
    a = sys.argv[1:]
    out = Path(a[a.index('--out') + 1]) if '--out' in a else ROOT / 'shader-gs'
    limit = int(a[a.index('--limit') + 1]) if '--limit' in a else None
    only = a[a.index('--only') + 1].lower() if '--only' in a else None
    jobs = int(a[a.index('--jobs') + 1]) if '--jobs' in a else 4
    stage = Path(a[a.index('--stage') + 1]) if '--stage' in a else None
    def src(p):   # the staged copy of a manifest file, when there is one
        # A relative manifest path is relative to the root folder (the game's working directory, the parent of
        # startup/), as write_shader_manifest.py writes it and the runtime reads it.
        if not Path(p).is_absolute(): p = str(ROOT.parent / p)
        if stage:
            try: s = stage / Path(p).resolve().relative_to(ROOT.resolve())
            except ValueError: return p
            if s.exists(): return str(s)
        return p
    groups = {}; ps_coord = []; seen = set()
    with open(ROOT / 'shader-manifest.tsv', encoding='utf-8') as f:
        for line in f:
            p = line.rstrip('\r\n').split('\t')
            if len(p) != 5 or p[4] in seen: continue
            seen.add(p[4])
            if p[1] == 'ps':
                isg = part(src(p[4]), b'ISG1')
                if isg and b'POINTCOORD\0' in isg: ps_coord.append((p[4], elements(isg)))
                continue
            if p[1] != 'vs': continue
            d = part(src(p[4]), b'OSG1')
            if d is None: print('no OSG1:', p[4]); continue
            k = fnv64(d); g = groups.setdefault(k, [elements(d), 0, Path(p[4]).name]); g[1] += 1
    print(f'{len(seen)} manifest files, {sum(g[1] for g in groups.values())} vertex shaders, {len(groups)} output signatures,'
          f' {len(ps_coord)} pixel shaders read POINTCOORD', flush=True)
    keys = sorted(groups, key=lambda k: -groups[k][1])
    if only: keys = [k for k in keys if f'{k:016x}' == only]
    if limit: keys = keys[:limit]
    out.mkdir(parents=True, exist_ok=True)
    def one(k):
        els, count, example = groups[k]
        try: text = hlsl(k, els, count, example)
        except ValueError as e: return k, f'skipped: {e}'
        src = out / f'pt-{k:016x}.hlsl'; dst = out / f'pt-{k:016x}.gs.dxil'
        src.write_text(text, encoding='utf-8', newline='\n')
        rc, msg = compile_gs(src, dst)
        if rc != 0 or not dst.exists(): return k, 'compile failed: ' + msg.splitlines()[0] if msg else 'compile failed'
        bad = check(k, els, dst)
        if bad: dst.unlink(); return k, 'check failed: ' + bad
        return k, None
    failed = 0
    with ThreadPoolExecutor(max_workers=max(1, min(jobs, 8))) as ex:
        res = dict(ex.map(one, keys))
    with open(out / 'point-gs.tsv', 'w', encoding='utf-8', newline='\n') as t:
        for k in keys:
            err = res[k]; failed += err is not None
            t.write(f'{k:016x}\t{groups[k][1]}\t{groups[k][2]}\t{"pt-%016x.gs.dxil" % k if err is None else err}\n')
            if err: print(f'{k:016x}: {err}')
    # The pixel shaders that read POINTCOORD: their inputs must be a register-exact prefix of a geometry shader's
    # outputs for the vertex shaders they pair with (unknown offline: report the layouts that fit).
    for path, pin in ps_coord:
        fits = []
        for k in keys:
            if res.get(k): continue
            go = {(e[0], e[1]): e for e in elements(part(out / f'pt-{k:016x}.gs.dxil', b'OSG1'))}
            if all(e[0] in ('SV_IsFrontFace', 'SV_SampleIndex', 'SV_Coverage') or
                   ((e[0], e[1]) in go and go[(e[0], e[1])][4] == e[4] and (go[(e[0], e[1])][5] & e[5]) == e[5]) for e in pin):
                fits.append(f'{k:016x}')
        print(f'pixel shader {Path(path).name}: inputs {[(e[0] + str(e[1]), e[4], e[5]) for e in pin]}; fits {len(fits)} layouts'
              f'{": " + ", ".join(fits[:6]) if fits else ""}')
    print(f'done: {len(keys) - failed} geometry shaders in {out}, {failed} failed')
    return 1 if failed else 0

if __name__ == '__main__': sys.exit(main())
