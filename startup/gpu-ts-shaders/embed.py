import sys, os, hashlib
out = ['/* Generated by gpu-ts-shaders/build.sh from gpu-ts-shaders/gpu_ts.hlsl (DXC, cs_6_0): do not edit. */',
       '#ifndef TOTK_HOST_NVN_GPU_TS_DXIL_H', '#define TOTK_HOST_NVN_GPU_TS_DXIL_H', '#include <stdint.h>']
for path in sys.argv[1:]:
    b = open(path, 'rb').read()
    name = 'boot_nvn_' + os.path.basename(path).split('.')[0] + '_dxil'
    out.append('/* %s: %d bytes, sha256 %s */' % (os.path.basename(path), len(b), hashlib.sha256(b).hexdigest()))
    out.append('static const uint8_t %s[%d] = {' % (name, len(b)))
    for i in range(0, len(b), 24):
        out.append('    ' + ','.join('0x%02x' % c for c in b[i:i + 24]) + ',')
    out.append('};')
out.append('#endif')
sys.stdout.buffer.write(('\r\n'.join(out) + '\r\n').encode('ascii'))   # CRLF, as the other generated DXIL headers
