# render-38d: replaces the generated DXIL block of host_gpu_render.h (between the BEGIN/END marker lines) with the
# bytes of indirect.cs.dxil. The block lives in host_gpu_render.h itself (not a header of its own) so the renderer
# keeps its existing header set. usage: embed_into.py <indirect.cs.dxil> <host_gpu_render.h>
import sys, hashlib
b = open(sys.argv[1], 'rb').read(); path = sys.argv[2]
s = open(path, encoding='utf-8', newline='').read()
nl = '\r\n' if '\r\n' in s else '\n'
begin = '/* BEGIN render-38d indirect DXIL: generated by indirect-shaders/build.sh from indirect.hlsl (DXC, cs_6_0), do not edit */'
end = '/* END render-38d indirect DXIL */'
out = [begin, '/* indirect.cs.dxil: %d bytes, sha256 %s */' % (len(b), hashlib.sha256(b).hexdigest()),
       'static const uint8_t boot_gpu_indirect_dxil[%d] = {' % len(b)]
for i in range(0, len(b), 24): out.append('    ' + ','.join('0x%02x' % c for c in b[i:i + 24]) + ',')
out += ['};', end]
i, j = s.index(begin), s.index(end) + len(end)
s = s[:i] + nl.join(out) + s[j:]
open(path, 'w', encoding='utf-8', newline='').write(s)
print(path, 'DXIL', len(b), 'bytes')
